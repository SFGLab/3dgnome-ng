"""Writes the arm configs of the cross line RNAPII comparison,
`design/2026-11-11-rnapii-release.md`.

One ini per line and arm, the production config with the data section of the inputs of
`playground/rnapii/crosscell_prep.py`. C is CTCF only, R is CTCF and RNAPII and M is R with
RNAPII loop ends near a CTCF anchor moved onto it. UC and UR are C and R on the uniform chain,
with the keys of `UNIFORM_CHAIN` and the contact cells from half a of the deep map of the line,
`data/_hic_half/a/<cell>.mcool` of `playground/thin_cooler.py --chromosomes`. Their structures
are scored against half b. UCN and URN are UC and UR with `[springs] loop_dropout = no`, the runs
of the panels on RNAPII loops, `design/uniform-chain.md`.

    python slurm/ensemble/crosscell_configs.py
"""

from __future__ import annotations

import configparser
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(ROOT))

from make_configs import CELLS  # noqa: E402
from make_configs import build as production  # noqa: E402

from gnome3d.production import UNIFORM_CHAIN  # noqa: E402

ARMS = ("C", "R", "M", "UC", "UR", "UCN", "URN")


def build(cell: str, arm: str) -> configparser.ConfigParser:
    """Returns the production config of `cell` with the loops and anchors of arm `arm`."""
    cfg = production(cell, "hic", None)
    data = cfg["data"]
    ctcf = f"{cell}_xc_ctcf_clusters_3+.bedpe"
    if arm.startswith("U"):
        for section, keys in UNIFORM_CHAIN.items():
            for key, value in keys.items():
                cfg[section][key] = str(value)
        data["contact_map"] = f"data/_hic_half/a/{cell}.mcool::/resolutions/5000"
        if arm.endswith("N"):
            cfg["springs"]["loop_dropout"] = "no"
        arm = arm[1:].removesuffix("N")
    if arm == "C":
        data["clusters"] = ctcf
        return cfg
    tag = "_absorbed" if arm == "M" else ""
    data["anchors"] = f"{cell}_xc_anchors_ctcf_rnapii{tag}.bed"
    data["clusters"] = f"{ctcf},{cell}_xc_rnapii{tag}_clusters_3+.bedpe"
    data["factors"] = "CTCF,RNAPOL2"
    cfg["springs"]["factor_strength"] = "1,1"
    return cfg


def _source_note(cell: str) -> str:
    """Returns the RNAPII source line of the prep record of the cell when another line stands in."""
    rec = ROOT / "data" / cell / f"{cell}_xc_prep.json"
    if not rec.is_file():
        rec = ROOT / "design" / "plans" / "rnapii-prep-records" / f"{cell}_xc_prep.json"
    src = str(json.loads(rec.read_text()).get("rnapii_source", ""))
    return f"# {src}\n" if src.startswith("RNAPII from") else ""


def main() -> None:
    out_dir = Path(__file__).resolve().parent
    for cell in CELLS:
        for arm in ARMS:
            path = out_dir / f"{cell.lower()}_xc_{arm}.ini"
            with path.open("w") as fh:
                fh.write(
                    f"# {cell} arm {arm} of the cross line RNAPII comparison. Generated by "
                    "slurm/ensemble/crosscell_configs.py; regenerate rather than edit.\n"
                )
                if arm not in ("C", "UC", "UCN"):
                    fh.write(_source_note(cell))
                fh.write("\n")
                build(cell, arm).write(fh)
            print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
