"""Writes the ensemble config of each cell line from `gnome3d.production.CANONICAL`.

python slurm/ensemble/make_configs.py
"""

import argparse
import configparser
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from gnome3d.production import CANONICAL, cell_data_section  # noqa: E402

CELLS = ["GM12878", "H1ESC", "HFFC6"]
BINSIZE = 25000

# The singleton source: Hi-C bin pairs, ChIA-PET singletons or both, see combine_singletons.py.
SINGLETONS = {
    "hic": "{cell}_hic_{kb}kb_singletons.bedpe",
    "chiapet": "{cell}_singletons_lessthan3.bedpe",
    "combined": "{cell}_combined_singletons.bedpe",
}

HEADER = """\
# {cell} ensemble with {singletons} singletons. Generated by slurm/ensemble/make_configs.py from
# gnome3d.production.CANONICAL. Edit that and regenerate.

"""


def build(
    cell: str,
    singletons: str,
    ev_weight: float | None,
) -> configparser.ConfigParser:
    cfg = configparser.ConfigParser()
    params = {k: dict(v) for k, v in CANONICAL.items()}
    params["data"] = cell_data_section(cell, "data")
    params["data"]["singletons"] = SINGLETONS[singletons].format(cell=cell, kb=BINSIZE // 1000)
    # The inter chromosomal singleton file is ChIA-PET and does not match a Hi-C source.
    params["data"]["singletons_inter"] = ""
    params["simulation_backend"]["multigpu_mode"] = "groups"
    params["simulation_backend"]["mc_executor_jax_bucket_shapes"] = "yes"
    params["subanchor_heatmap"]["heat_min_reduction"] = "0.001"
    if ev_weight is not None:
        # A lower weight lets pairs with strong attraction approach. The weight is swept here, not the
        # radius.
        params["excluded_volume"]["weight"] = str(ev_weight)

    for sec, kv in params.items():
        cfg[sec] = {str(k): str(v) for k, v in kv.items()}
    return cfg


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--singletons", choices=sorted(SINGLETONS), default="hic")
    ap.add_argument(
        "--ev-weight",
        type=float,
        default=None,
        help="override [excluded_volume] weight; names the file accordingly",
    )
    args = ap.parse_args()

    out_dir = Path(__file__).resolve().parent
    for cell in CELLS:
        cfg = build(cell, args.singletons, args.ev_weight)
        tag = "" if args.ev_weight is None else f"_ev{args.ev_weight:g}".replace(".", "p")
        path = out_dir / f"{cell.lower()}_{args.singletons}_arcs{tag}.ini"
        with path.open("w") as fh:
            fh.write(HEADER.format(cell=cell, singletons=args.singletons))
            cfg.write(fh)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
